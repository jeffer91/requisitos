"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),path=require("node:path"),vm=require("node:vm");
const ctx={window:{},Date,Intl,Set,Math};vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.resolve(__dirname,"../Actas/actas.issue-date.js"),"utf8"),ctx);
const cal=ctx.window.ActasIssueDate;
assert.equal(cal.forPeriod("2025-10__2026-03").date,"2026-05-29","Octubre–marzo: último día hábil de mayo");
assert.equal(cal.forPeriod("2026-04__2026-09").date,"2026-11-30","Abril–septiembre: último día hábil de noviembre");
assert.equal(cal.forPeriod("2025-10__2026-03").holidaysVerified,true,"Calendario ecuatoriano 2026 verificado");
assert.equal(cal.forPeriod("2026-10__2027-03").date,"2027-05-31","Octubre–marzo del siguiente ciclo");
assert.equal(cal.forPeriod("2026-10__2027-03").holidaysVerified,true,"Calendario de feriados nacionales 2027 verificado");
assert.equal(cal.mayRegister("2025-10__2026-03",new Date("2026-05-28T15:00:00-05:00")),false,"No se registra anticipadamente");
assert.equal(cal.mayRegister("2025-10__2026-03",new Date("2026-05-29T10:00:00-05:00")),true,"Se registra en fecha de emisión");
assert.equal(cal.mayRegister("2026-04__2026-09",new Date("2026-10-30T14:00:00-05:00")),false,"No se emite oficialmente en octubre un acta programada para noviembre");
assert.throws(()=>cal.forPeriod("2026-13__2026-03"),/inválid/);
assert.throws(()=>cal.forPeriod("2026-04__2025-09"),/inválid/);
const out=cal.forPeriod("2025-10__2026-03",["2026-05-29"]);
assert.equal(out.date,"2026-05-28","Excluye días no laborables adicionales configurados");
const businessDay=(date)=>{const d=new Date(date+"T12:00:00Z"),n=d.getUTCDay();return n!==0&&n!==6;};
assert.ok(businessDay(cal.forPeriod("2025-10__2026-03").date));
assert.ok(businessDay(cal.forPeriod("2026-04__2026-09").date));
const pdf=fs.readFileSync(path.resolve(__dirname,"../Actas/actas.pdf.js"),"utf8");
const word=fs.readFileSync(path.resolve(__dirname,"../Actas/actas.docx.js"),"utf8");
const html=fs.readFileSync(path.resolve(__dirname,"../Actas/actas.document.js"),"utf8");
const app=fs.readFileSync(path.resolve(__dirname,"../Actas/actas.app.js"),"utf8");
assert.match(pdf,/Unidad de Titulación y/);assert.match(pdf,/Eficiencia Terminal/);
assert.match(pdf,/Acta de Titulación por Examen Complexivo/);
assert.match(word,/Unidad de Titulación y/);assert.match(word,/bold:false,vm:"restart"/);
assert.match(word,/Acta de Titulación por Examen Complexivo/);
assert.match(html,/Unidad de Titulación y Eficiencia Terminal/);
assert.match(html,/\.head \.center\{[^}]*font-weight:normal/);
assert.match(html,/Acta de Titulación por Examen Complexivo/);
assert.match(app,/issue:w\.ActasIssueDate\.forPeriod\(S\.periodo\)\.date/);
assert.match(app,/fechaEmision:w\.ActasIssueDate\.forPeriod\(S\.periodo\)\.date/);
console.log("VERIFICACIÓN FECHA ACTAS: OK (títulos, tipografía, dos meses, días hábiles, emisión no anticipada)");
